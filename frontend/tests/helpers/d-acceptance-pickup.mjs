import assert from 'node:assert/strict'
import { buyerReopensOrder } from './d-acceptance-navigation.mjs'

const openSellerPayments = async seller => {
  await seller.getByRole('link', { name: 'Đơn mua của tôi', exact: true }).filter({ visible: true }).first().click()
  await seller.getByRole('navigation', { name: 'Tài khoản', exact: true }).getByRole('link', { name: 'Xác nhận nhận tiền', exact: true }).click()
}

export async function pickupFromHome({ buyer, seller, fixture, links, image }) {
  await buyer.setViewportSize({ width: 1440, height: 1100 })
  await buyer.getByRole('link', { name: 'Trang chủ', exact: true }).filter({ visible: true }).first().click()
  await buyer.locator('article').filter({ hasText: fixture.pickupTitle }).locator('h3').click()
  await buyer.locator('.product-actions').getByRole('button', { name: 'Mua ngay', exact: true }).click()
  await buyer.getByRole('radio', { name: /Tự đến lấy/ }).check()
  await buyer.locator('#receiver-name').fill('Pickup Buyer'); await buyer.locator('#receiver-phone').fill('0900000111')
  const response = buyer.waitForResponse(r => r.url().endsWith('/api/v1/orders') && r.request().method() === 'POST')
  await buyer.getByRole('button', { name: 'Đặt hàng và giữ món', exact: true }).click()
  const ordered = (await (await response).json()).data, id = ordered.orderId
  assert.equal(ordered.deliveryFeeDecimal, '0.00'); assert.equal(ordered.totalAmountDecimal, '88888.88')
  await buyer.getByRole('button', { name: 'Theo dõi đơn hàng', exact: true }).click()
  await openSellerPayments(seller)
  await seller.getByRole('link', { name: 'Đơn chờ chấp nhận', exact: true }).click()
  await seller.getByRole('row').filter({ hasText: `#${id}` }).getByRole('button', { name: 'Chấp nhận', exact: true }).click()
  await seller.getByRole('button', { name: 'Xác nhận', exact: true }).click()
  await seller.getByRole('button', { name: 'Đóng', exact: true }).click()
  await buyer.getByRole('button', { name: 'Làm mới', exact: true }).click()
  await buyer.getByRole('link', { name: 'Thanh toán / Báo chuyển tiền', exact: true }).click()
  await buyer.locator('#d03-proof').setInputFiles({ name: 'pickup-receipt.png', mimeType: 'image/png', buffer: image })
  await buyer.getByRole('button', { name: 'Tôi đã chuyển tiền', exact: true }).click()
  await buyer.getByText('Đã gửi thông báo chuyển khoản cho người bán.', { exact: true }).first().waitFor()
  await openSellerPayments(seller)
  await seller.locator(`a[href="/seller/orders/${id}/payment"]`).click()
  const stale = await seller.context().newPage()
  try {
    await stale.goto(new URL(seller.url()).origin + '/')
    await openSellerPayments(stale)
    await stale.locator(`a[href="/seller/orders/${id}/payment"]`).click()
    await stale.getByRole('button', { name: 'Đã nhận đủ tiền', exact: true }).waitFor()
    await seller.getByRole('textbox', { name: 'Ghi chú đối chiếu', exact: true }).fill('Nghiem thu: chua thay giao dich, kiem tra lai bien lai.')
    await seller.getByRole('button', { name: 'Chưa nhận được tiền', exact: true }).click()
    const rejected = seller.waitForResponse(r => r.url().endsWith(`/seller/orders/${id}/payment`) && r.request().method() === 'PATCH')
    await seller.getByRole('button', { name: 'Lưu kết quả đối chiếu', exact: true }).click()
    assert.equal((await rejected).status(), 200)
    await buyer.getByRole('button', { name: 'Tải lại trạng thái', exact: true }).click()
    await buyer.getByText(/Người bán chưa nhận được tiền. Kiểm tra giao dịch/).waitFor()
    await buyer.locator('#d03-proof').setInputFiles({ name: 'corrected-receipt.png', mimeType: 'image/png', buffer: image })
    await buyer.getByRole('button', { name: 'Tôi đã chuyển tiền', exact: true }).click()
    await buyer.getByText('Đã gửi thông báo chuyển khoản cho người bán.', { exact: true }).first().waitFor()
    await stale.getByRole('button', { name: 'Đã nhận đủ tiền', exact: true }).click()
    const conflict = stale.waitForResponse(r => r.url().endsWith(`/seller/orders/${id}/payment`) && r.request().method() === 'PATCH')
    await stale.getByRole('button', { name: 'Lưu kết quả đối chiếu', exact: true }).click()
    const response = await conflict
    assert.equal(response.status(), 409); assert.equal((await response.json()).code, 'PAYMENT_REPORT_CHANGED')
    await stale.getByRole('alert').waitFor()
    assert.equal((await links.read({ listingId: fixture.pickupListingId, orderId: id })).order.Status, 'WAITING_PAYMENT')
    console.log(`PASS PAYMENT UI Order#${id}: rejected receipt -> buyer sees reason/reports again; stale seller tab gets real 409 and cannot confirm old report`)
  } finally { await stale.close() }
  await seller.getByRole('button', { name: 'Tải lại', exact: true }).click()
  await seller.getByRole('button', { name: 'Đã nhận đủ tiền', exact: true }).click()
  await seller.getByRole('button', { name: 'Lưu kết quả đối chiếu', exact: true }).click()
  await seller.getByText('Đã xác nhận nhận đủ tiền', { exact: true }).first().waitFor()
  await seller.getByRole('link', { name: 'Theo dõi đơn hàng', exact: true }).click()
  await seller.getByRole('heading', { name: 'Đã thanh toán · tự đến lấy', exact: true }).waitFor()
  assert.equal(await seller.getByRole('button', { name: 'Xác nhận sẵn sàng giao hàng', exact: true }).count(), 0)
  await buyer.getByRole('button', { name: 'Tải lại trạng thái', exact: true }).click()
  await buyer.getByRole('link', { name: 'Quay lại đơn hàng / Hủy đơn', exact: true }).click()
  await buyer.getByRole('link', { name: 'Tạo yêu cầu hoàn tiền', exact: true }).waitFor()
  assert.equal(await buyer.getByRole('button', { name: 'Tiếp tục hủy đơn', exact: true }).count(), 0)
  await buyer.getByRole('link', { name: 'Tạo yêu cầu hoàn tiền', exact: true }).click()
  await buyer.getByRole('heading', { name: `Yêu cầu hoàn tiền cho đơn #${id}`, exact: true }).waitFor()
  assert.equal((await links.read({ listingId: fixture.pickupListingId, orderId: id })).refunds, 0)
  await buyer.getByRole('link', { name: 'Quay lại theo dõi đơn hàng', exact: true }).click()
  console.log(`PASS D02 paid UI Order#${id}: cancellation links to correct B06 form; opening form creates no refund and does not cancel/reopen listing`)
  await buyerReopensOrder(buyer, id)
  await buyer.getByRole('heading', { name: 'Đã thanh toán · tự đến lấy', exact: true }).waitFor()
  assert.equal(await buyer.getByRole('button', { name: 'Tạo mã giao hàng', exact: true }).count(), 0)
  const s = await links.read({ listingId: fixture.pickupListingId, orderId: id })
  assert.equal(s.order.DeliveryMethod, 'PICKUP'); assert.equal(s.order.Status, 'PAID')
  assert.equal(s.order.DeliveryFee, '0.00'); assert.equal(s.deliveries.length, 0); assert.equal(s.commissions.length, 0)
  const preview = await links.api(buyer, `/api/v1/orders/${id}/received-preview`)
  assert.equal(preview.status(), 200); assert.equal((await preview.json()).data.policy.code, 'PICKUP_HANDOVER_UNAVAILABLE')
  console.log(`BLOCKED PICKUP UI Order#${id}: Home -> D01 -> C05 -> D03 -> D04 PAID; zero fee/trip/OTP; no C07 pickup handover UI, D06 policy PICKUP_HANDOVER_UNAVAILABLE.`)
  return { orderId: id, listingId: fixture.pickupListingId, status: 'PAID', blocked: 'PICKUP_HANDOVER_UNAVAILABLE' }
}
